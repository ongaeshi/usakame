# Usakame Retro Game Engine - Sample Script
# ==========================================

$x = 60
$y = 60
$t = 0
$flip_x = false

def update
  $t += 1

  # 矢印キー入力 (0:左, 1:右, 2:上, 3:下)
  if btn(0)
    $x -= 1
    $flip_x = true
  end
  if btn(1)
    $x += 1
    $flip_x = false
  end
  if btn(2)
    $y -= 1
  end
  if btn(3)
    $y += 1
  end

  # 画面端のクランプ (0..120)
  $x = 0 if $x < 0
  $x = 120 if $x > 120
  $y = 0 if $y < 0
  $y = 120 if $y > 120
end

def draw
  # 1: ダークブルーで画面クリア
  cls(1)

  # 背景の星をきらめかせる
  pset(20, 15, ($t / 15) % 2 == 0 ? 7 : 6)
  pset(95, 25, ($t / 20) % 2 == 0 ? 10 : 5)
  pset(40, 80, 7)
  pset(110, 90, 7)

  # 地面を描画 (3: ダークグリーン, 11: ライトグリーン)
  rectfill(0, 112, 128, 16, 3)
  rectfill(0, 112, 128, 2, 11)

  # タイトルテキスト (7: ホワイト, 10: イエロー)
  print_text("USAKAME ENGINE", 20, 6, 7)
  print_text("ARROW KEYS TO MOVE", 12, 16, 10)

  # カメ（スプライト1）がゆっくり歩く
  kame_x = ($t / 4) % 112
  spr(1, kame_x, 104, false, false)

  # ウサギ（スプライト0）を描画（移動中や時間経過でぴょこぴょこ跳ねる）
  bounce = (($t / 8) % 2 == 0) ? 0 : -2
  spr(0, $x, $y + bounce, $flip_x, false)
end

