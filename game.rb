# Usakame Retro Game Engine - Sample Script (256x256, 16x16 Sprites)
# ==========================================

$x = 120
$y = 192
$t = 0
$flip_x = false

def update
  $t += 1

  # 矢印キー入力 (0:左, 1:右, 2:上, 3:下)
  if btn(0)
    $x -= 2
    $flip_x = true
  end
  if btn(1)
    $x += 2
    $flip_x = false
  end
  if btn(2)
    $y -= 2
  end
  if btn(3)
    $y += 2
  end

  # 画面端のクランプ (0..240)
  $x = 0 if $x < 0
  $x = 240 if $x > 240
  $y = 0 if $y < 0
  $y = 240 if $y > 240
end

def draw
  # 1: ダークブルーで画面クリア (256x256)
  cls(1)

  # 背景の星をきらめかせる
  pset(32, 24, ($t / 15) % 2 == 0 ? 7 : 6)
  pset(180, 36, ($t / 20) % 2 == 0 ? 10 : 5)
  pset(80, 64, 7)
  pset(220, 50, 7)

  # 地面を描画 (3: ダークグリーン, 11: ライトグリーン)
  rectfill(0, 224, 256, 32, 3)
  rectfill(0, 224, 256, 3, 11)

  # タイトルテキスト (7: ホワイト, 10: イエロー)
  print_text("USAKAME ENGINE (256x256 / 16x16)", 48, 12, 7)
  print_text("ARROW KEYS TO MOVE / EMOJI & 16x16 SPRITES", 24, 24, 10)

  # 標準内蔵 16x16 絵文字スプライトで背景やアイテムを描画
  spr("🌙", 216, 16)
  spr("🏰", 20, 208)
  spr("🌲", 44, 208)
  spr("🌲", 200, 208)
  spr("🍎", 160, 208)

  # カメ（スプライト1 または "🐢"）がゆっくり歩く
  kame_x = ($t / 2) % 240
  spr(1, kame_x, 208, false, false)

  # ウサギ（スプライト0）を描画（ぴょこぴょこ跳ねる）
  bounce = (($t / 8) % 2 == 0) ? 0 : -3
  spr(0, $x, $y + bounce, $flip_x, false)
end

