# ==============================================================================
# 🏃 大玉転がし (Big Ball Rolling) - 16-Bit Dot Art Demo 🔴⚪
# ------------------------------------------------------------------------------
# 実行コマンド: uk run examples/big_ball.rb
#
# 【特徴】
# - 16bitレトロゲーム黄金期スタイルの 32x32 ドット絵スプライト
# - 大玉転がしの玉 (32x32) と 懸命に押す女の子 (32x32, 2フレームアニメーション)
# - 共通16色パレット (@PALETTE 0) による色彩設計
# - 十字キー (左右 / A・D): 大玉を転がして前進・後退
# - スペースキー / Zキー: 拡大鑑賞モード切替 (1x フィールド / 3x ドット鑑賞)
# ==============================================================================

config(
  width: 256,
  height: 224,
  scale: 2.5,
  title: "🏃 大玉転がし (Big Ball Rolling) 🔴⚪"
)

# 状態管理
$px = 60            # 女の子のX座標 (Integer)
$py = 120           # 接地Y座標 (Integer)
$speed = 2
$anim_timer = 0
$anim_frame = 0     # 0: ポーズ1, 1: ポーズ2
$moving = false
$zoom_mode = false
$cloud_x = 0
$cloud_timer = 0

def update
  $cloud_timer += 1
  if $cloud_timer >= 3
    $cloud_timer = 0
    $cloud_x = ($cloud_x + 1) % 256
  end

  # 移動操作
  dx = 0
  dx += 1 if btn(1) || btn("d") || btn("right") # 右
  dx -= 1 if btn(0) || btn("a") || btn("left")  # 左

  if dx != 0
    $moving = true
    $px += dx * $speed
    $px = 8 if $px < 8
    $px = 170 if $px > 170

    $anim_timer += 1
    if $anim_timer >= 6
      $anim_timer = 0
      $anim_frame = ($anim_frame + 1) % 2
    end
  else
    $moving = false
    $anim_frame = 0
    $anim_timer = 0
  end

  # スペースキーまたはZキーで拡大鑑賞モード切り替え
  if btnp("space") || btnp("z") || btnp(4)
    $zoom_mode = !$zoom_mode
  end
end

def draw
  if $zoom_mode
    draw_zoom_view
  else
    draw_field_view
  end
end

# ------------------------------------------------------------------------------
# 通常フィールドビュー
# ------------------------------------------------------------------------------
def draw_field_view
  # 1. 青空 (E: #b4c4d4 淡いスカイブルー)
  cls(14)

  # 2. 遠景の白い雲 (F: #ffffff 純白)
  draw_cloud($cloud_x - 30, 24, 40)
  draw_cloud(($cloud_x + 120) % 280 - 30, 42, 28)

  # 3. 運動会の三角旗（ガーランド）
  draw_garland(14)

  # 4. 遠景の山・校舎・木々 (D: #708098, C: #304884)
  rectfill(0, 78, 256, 32, 13)    # 遠くの山影 (D)
  rectfill(0, 92, 256, 18, 12)    # 手前の木々 (C)
  # 校舎のシルエット
  rectfill(80, 68, 70, 24, 6)     # 校舎壁 (6: クリーム)
  rectfill(84, 72, 62, 20, 1)     # 窓枠・屋根 (1: 濃茶)
  rectfill(110, 56, 10, 12, 9)    # 時計塔 (9: 赤)
  rectfill(113, 60, 4, 4, 15)     # 時計盤 (15: 白)

  # 5. グラウンド (2: #8a482e 土ブラウン)
  rectfill(0, 110, 256, 114, 2)
  # トラックの白線（レーン） (15: 純白)
  rectfill(0, 116, 256, 2, 15)
  rectfill(0, 154, 256, 2, 15)
  rectfill(0, 192, 256, 2, 15)

  # 6. 接地影 (0: 最深シャドウ)
  ovalfill($px + 4, $py + 30, 12, 3, 0)
  ovalfill($px + 20, $py + 30, 10, 3, 0)
  ovalfill($px + 24 + 16, $py + 30, 16, 4, 0)

  # 7. キャラクターと大玉の描画
  girl_spr = ($anim_frame == 0) ? 2 : 4
  spr(girl_spr, $px, $py, false, false, 0, 1.0)

  # 大玉（女の子の手が X+24 で接触）
  spr(0, $px + 24, $py, false, false, 0, 1.0)

  # 8. UI テキスト案内
  rectfill(0, 0, 256, 11, 0)
  print_text("RUN! BIG BALL", 8, 2, 15)
  print_text("ARROWS: ROLL   SPACE: ZOOM", 92, 2, 10)

  # 足元の砂煙エフェクト（移動時）
  if $moving && ($anim_timer % 3 == 0)
    circfill($px + rand(2..6), $py + 29 + rand(0..2), 1, 6)
  end
end

def draw_cloud(cx, cy, cw)
  circfill(cx, cy, cw / 3, 15)
  circfill(cx + cw / 3, cy - 3, cw * 2 / 5, 15)
  circfill(cx + cw * 7 / 10, cy, cw / 3, 15)
  rectfill(cx, cy, cw * 7 / 10, cw / 4, 15)
end

def draw_garland(y)
  line(0, y, 256, y + 4, 0)
  # 運動会のカラフルな三角旗 (赤9, 白15, 黄3, 紺12, 桃10)
  flag_colors = [9, 15, 3, 12, 10, 15]
  i = 0
  x = 8
  while x < 250
    col = flag_colors[i % 6]
    tri(x, y + 1, x + 10, y + 2, x + 5, y + 9, col)
    x += 16
    i += 1
  end
end

def tri(x1, y1, x2, y2, x3, y3, col)
  line(x1, y1, x2, y2, col)
  line(x2, y2, x3, y3, col)
  line(x3, y3, x1, y1, col)
  line(x1 + 1, y1 + 1, x2 - 1, y2 + 1, col)
  line(x1 + 2, y1 + 2, x3, y3 - 1, col)
end

# ------------------------------------------------------------------------------
# 拡大鑑賞ビュー (Zoom 3x)
# ------------------------------------------------------------------------------
def draw_zoom_view
  rectfill(0, 0, 256, 224, 0) # 黒背景

  # ヘッダー情報
  print_text("== 16-BIT PIXEL ART INSPECTOR ==", 32, 8, 10)
  print_text("Motif: Big Ball (32x32) & Girl (32x32)", 24, 20, 15)
  print_text("@PALETTE 0: Shared 16 Colors", 48, 30, 6)

  # 3倍拡大で並べて表示
  # 女の子 (スプライト 2)
  rectfill(16, 46, 100, 100, 11) # 濃紺枠 (B)
  rectfill(18, 48, 96, 96, 1)     # 濃茶背景 (1)
  spr(2, 20, 48, false, false, 0, 3.0)
  print_text("GIRL (32x32)", 32, 150, 15)

  # 大玉 (スプライト 0)
  rectfill(128, 46, 100, 100, 11) # 濃紺枠 (B)
  rectfill(130, 48, 96, 96, 1)     # 濃茶背景 (1)
  spr(0, 132, 48, false, false, 0, 3.0)
  print_text("BIG BALL (32x32)", 136, 150, 15)

  # 合体配置のプレビュー (下部 1倍)
  rectfill(16, 166, 224, 44, 11)
  rectfill(18, 168, 220, 40, 0)
  print_text("< COMBINED CONTACT SCENE >", 24, 172, 10)
  # 合体スプライト
  spr(2, 88, 174, false, false, 0, 1.0)
  spr(0, 112, 174, false, false, 0, 1.0)
  print_text("Hand pushes directly into ball surface", 32, 198, 6)

  print_text("[SPACE]: BACK TO FIELD", 72, 212, 10)
end

