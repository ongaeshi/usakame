# ==============================================================================
# 🗡️ 16-Bit Retro RPG Character Walk Demo 🌿
# ------------------------------------------------------------------------------
# 実行コマンド: uk run examples/rpg_walk.rb
#
# 【特徴】
# - 16ビット名作RPGスタイルの 16x24 ドット絵キャラクター
# - 女の子（魔法少女風）と男の子（冒険者風）の2キャラクターを収録
# - 十字キー (矢印 / WASD): 四方向に歩行
# - Cキー / 数字1・2キー: 操作キャラクター切り替え
# - スペースキー: 拡大鑑賞モード切替 (1x / 3x ドット鑑賞ビュー)
# ==============================================================================

config(
  width: 256,
  height: 224,
  scale: 2.5,
  title: "🗡️ 16-Bit RPG Character Walk Demo 🌿"
)

# プレイヤー状態
$px = 120.0
$py = 96.0
$speed = 1.2
$flip_x = false
$anim_timer = 0
$anim_frame = 0 # 0: 立ち, 1: 歩行1, 2: 立ち, 3: 歩行2
$moving = false
$char_id = 0    # 0: 女の子 (base: 0), 1: 男の子 (base: 8)
$zoom_mode = false

def update
  # 移動入力
  dx = 0
  dy = 0
  dx -= 1 if btn(0) # 左
  dx += 1 if btn(1) # 右
  dy -= 1 if btn(2) # 上
  dy += 1 if btn(3) # 下

  $moving = (dx != 0 || dy != 0)

  if $moving
    if dx != 0 && dy != 0
      len = Math.sqrt(dx * dx + dy * dy)
      dx = (dx / len)
      dy = (dy / len)
    end

    $px += dx * $speed
    $py += dy * $speed

    $px = [[$px, 8].max, 232].min
    $py = [[$py, 16].max, 184].min

    $flip_x = true if dx < 0
    $flip_x = false if dx > 0

    $anim_timer += 1
    if $anim_timer >= 8
      $anim_timer = 0
      $anim_frame = ($anim_frame + 1) % 4
    end
  else
    $anim_frame = 0
    $anim_timer = 0
  end

  # キャラクター切り替え (Cキー または Xキー / 1キー / 2キー)
  if btnp("c") || btnp(:c) || btnp("x") || btnp(5) || btnp("1") || btnp("2")
    $char_id = ($char_id == 0) ? 1 : 0
  end

  # スペースキーで拡大鑑賞モード切替 (Space または Zキー)
  if btnp("space") || btnp("z") || btnp(4)
    $zoom_mode = !$zoom_mode
  end
end

def draw
  cls(1)

  if $zoom_mode
    draw_zoom_view
  else
    draw_field_view
  end
end

def current_sprite_id
  base = ($char_id == 0) ? 0 : 8
  offset = case $anim_frame
           when 1 then 2
           when 3 then 4
           else 0
           end
  base + offset
end

def draw_field_view
  # 石畳フロアの描画
  14.times do |ty|
    16.times do |tx|
      col = ((tx + ty) % 2 == 0) ? 5 : 0
      rectfill(tx * 16, ty * 16, 16, 16, col)
      rect(tx * 16, ty * 16, 16, 16, 1)
    end
  end

  # 足元シャドウ
  ovalfill(($px + 2).to_i, ($py + 21).to_i, 12, 5, 0)

  # キャラクタースプライト描画
  spr(current_sprite_id, $px.to_i, $py.to_i, $flip_x, false)

  # UI表示
  rectfill(0, 0, 256, 18, 0)
  rect(0, 0, 256, 18, 11)
  char_name = ($char_id == 0) ? "GIRL (MAGE)" : "BOY (ADVENTURER)"
  print_text("16-BIT RPG WALK DEMO", 8, 5, 7)
  print_text("[C] CHAR: #{char_name}", 138, 5, 10)

  rectfill(0, 206, 256, 18, 0)
  state_str = $moving ? "MOVING (FRAME #{$anim_frame})" : "IDLE"
  print_text("ARROW/WASD: MOVE | #{state_str} | [SPACE] ZOOM", 8, 211, 6)
end

def draw_zoom_view
  rectfill(0, 0, 256, 224, 0)

  print_text("SPRITE VIEWER (16x24 PIXELS)", 16, 8, 10)
  print_text("PRESS SPACE TO RETURN", 124, 8, 6)

  # 女の子 (上段)
  print_text("< GIRL: GREEN HAIR & RED DRESS >", 16, 24, 11)
  [
    { title: "WALK 1", id: 2, x: 28,  y: 36 },
    { title: "IDLE",   id: 0, x: 104, y: 36 },
    { title: "WALK 2", id: 4, x: 180, y: 36 }
  ].each do |p|
    rectfill(p[:x] - 8, p[:y] + 74, 64, 12, 5)
    spr(p[:id], p[:x], p[:y], false, false, 0, 3.0)
    print_text(p[:title], p[:x] + 4, p[:y] + 76, 7)
  end

  # 男の子 (下段)
  print_text("< BOY: BANDANA & LEATHER VEST >", 16, 124, 9)
  [
    { title: "WALK 1", id: 10, x: 28,  y: 136 },
    { title: "IDLE",   id: 8,  x: 104, y: 136 },
    { title: "WALK 2", id: 12, x: 180, y: 136 }
  ].each do |p|
    rectfill(p[:x] - 8, p[:y] + 74, 64, 12, 5)
    spr(p[:id], p[:x], p[:y], false, false, 0, 3.0)
    print_text(p[:title], p[:x] + 4, p[:y] + 76, 7)
  end
end

